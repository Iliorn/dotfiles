#!/bin/sh
# Decide where the screens and workspaces belong, and write that decision to a
# FILE that hyprland.conf sources last.
#
# WHY A FILE. The old setup applied the lid handover with `hyprctl keyword`,
# which only changes the RUNNING config. Any `hyprctl reload` — from editing a
# config, from another tool, from a script — re-read host.conf, re-enabled the
# panel and dragged the pinned workspaces back onto a lid that was shut. The
# rule is now simply: nothing about the screens lives only in memory.
#
# WHY GENERATED AND NOT HAND-WRITTEN PER MACHINE. The panel is named eDP-1 on
# the T480 and LVDS-1 on the Sandy Bridge X220s, and the external is whatever
# port happens to be used that day. Both are detected, so this file and
# hyprland.conf are identical on every laptop, and a new machine needs no
# host.conf entry to get the same behaviour.
#
# THE POLICY, which is the part worth arguing about:
#   - 1-3 live on the laptop panel, 4-9 on the external screen. Fixed, so
#     super+1..9 always lands the same place.
#   - Docked, the external is primary: new windows open there (workspace 4 is
#     its default) and that is where the session starts.
#   - Lid shut while docked: the panel is disabled, so Hyprland moves 1-3
#     across. Opening the lid brings them home, because the pinning is still
#     declared. This is the one thing that must survive a reload.
#   - Alone (no external): nothing is pinned at all. Every workspace belongs
#     to the only screen there is.
#   - Unplugged while shut: the panel is re-enabled rather than left with no
#     output anywhere. logind may suspend first; either way there is a way back.
#
# Placement — whether the external sits above, left or right — is NOT decided
# here. That is taste and it changes per desk, so it stays one line in
# host.conf. See host.example.conf.
set -eu

hypr_dir="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
state_dir="$hypr_dir/state"
out="$state_dir/screens.conf"
lid_flag="$state_dir/lid-closed"
mkdir -p "$state_dir"

# The panel is read from `monitors all` because we may have disabled it
# ourselves; the external from `monitors`, which lists only what is live, so an
# unplugged screen Hyprland still remembers cannot be pinned to.
panel=$(hyprctl monitors all | awk '/^Monitor (eDP|LVDS|DSI)/ { print $2; exit }')
ext=$(hyprctl monitors | awk '/^Monitor /{ if ($2 !~ /^(eDP|LVDS|DSI)/) { print $2; exit } }')

tmp="$out.new"
{
    echo "# Generated by scripts/screens.sh — do not edit, it is rewritten."
    echo "# panel=${panel:-none} external=${ext:-none} lid=$([ -f "$lid_flag" ] && echo closed || echo open)"

    # The panel gets a rule BY NAME, which is the point of detecting it:
    # host.conf can then carry a single nameless catch-all for the external
    # without that catch-all also swallowing the panel.
    if [ -n "$panel" ]; then
        if [ -f "$lid_flag" ] && [ -n "$ext" ]; then
            # Shut and docked: hand the session over. Without this the
            # workspaces on the panel go dark and stay where nobody sees them.
            echo "monitor = $panel, disable"
        else
            # Open, or shut with nowhere else to draw. `preferred` is the
            # panel's native mode on every one of these laptops.
            echo "monitor = $panel, preferred, auto, 1"
        fi
    fi

    if [ -n "$panel" ] && [ -n "$ext" ]; then
        echo "workspace = 1, monitor:$panel, default:true"
        echo "workspace = 2, monitor:$panel"
        echo "workspace = 3, monitor:$panel"
        echo "workspace = 4, monitor:$ext, default:true"
        for w in 5 6 7 8 9; do
            echo "workspace = $w, monitor:$ext"
        done
    fi
} > "$tmp"

# Only reload when the decision actually changed. A reload emits monitor
# events of its own, and acting on those would loop.
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
    rm -f "$tmp"
else
    mv "$tmp" "$out"
    hyprctl reload >/dev/null
fi

# Startup only: begin where the eyes are. Docked that is the external screen.
if [ "${1:-}" = "startup" ]; then
    if [ -n "$ext" ]; then
        hyprctl dispatch workspace 4 >/dev/null
    else
        hyprctl dispatch workspace 1 >/dev/null
    fi
fi
